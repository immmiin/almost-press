// Extracts seal / icon glyph outlines from Shippori Mincho B1 ExtraBold (OFL) into src/design/glyphs.ts,
// so seals and seal-stamp buttons render immediately without loading a 15 MB CJK font at runtime.
// Run: node scripts/extract-glyphs.mjs  (needs scripts/.cache/ShipporiMinchoB1-ExtraBold.ttf)
import { parse } from '../node_modules/opentype.js/dist/opentype.mjs';
import { readFile, writeFile } from 'node:fs/promises';

const CHARS = '殆滲暈霞波瀑碎映反融點印刷頁巻綴忘墨紙音言戻進消複転夢門跋出開閉號第一二三四五六七八九十〇零壱弐参拾頁鈴止選版色朱粒漂紙床地字鎖册冊見本表裏解ほぼ印所0123456789#';
const buf = await readFile('scripts/.cache/ShipporiMinchoB1-ExtraBold.ttf');
const font = parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const asc = font.ascender / font.unitsPerEm;
const out = {};
for (const ch of [...new Set(CHARS)]) {
  const g = font.charToGlyph(ch);
  if (!g || g.index === 0) { console.warn('missing', ch); continue; }
  const p = g.getPath(0, asc * 100, 100);
  const bb = p.getBoundingBox();
  out[ch] = { d: p.toPathData(1), w: +(g.advanceWidth / font.unitsPerEm * 100).toFixed(1), bb: [bb.x1, bb.y1, bb.x2, bb.y2].map((v) => +v.toFixed(1)) };
}
const src = `// Generated by scripts/extract-glyphs.mjs from Shippori Mincho B1 ExtraBold (SIL OFL 1.1).
// Each glyph: SVG path in a 100-unit em box (y down), advance width and bounding box.
export interface Glyph { d: string; w: number; bb: [number, number, number, number] }
export const GLYPHS: Record<string, Glyph> = ${JSON.stringify(out)};
`;
await writeFile('src/design/glyphs.ts', src);
console.log(Object.keys(out).length, 'glyphs', (src.length / 1024).toFixed(0) + 'KB');
